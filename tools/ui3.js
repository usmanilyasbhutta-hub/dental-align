  await p.waitForTimeout(400);
  await S('1_home_empty');
  await p.fill('.searchfield input', 'dh-0147');
  await p.waitForTimeout(200);
  await S('2_home_add');
  await p.click('text=Add patient DH-0147');
  await p.click('.tile-add');
  await p.waitForTimeout(400);
  await S('3_sheet');
  await p.click('.sheet >> text=Right Buccal');
  await p.waitForTimeout(1800);
  await S('4_cam_baseline');
  await p.click('.shutter');
  await p.waitForSelector('text=Baseline saved');
